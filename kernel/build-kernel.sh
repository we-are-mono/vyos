#!/bin/bash
# Cross-build the Mono Gateway VyOS kernel .debs and the ASK kernel modules.
# Runs inside the mono-vyos-cross container (see build.sh); expects
# prepare-tree.sh to have produced build/kernel-series (branch mono).
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
TOP=$(cd "$HERE/.." && pwd)
. "$TOP/pins.sh"


TREE=$BUILD/kernel-series
KDIR=$BUILD/kernel            # debs land here, source in $KDIR/src
SRC=$KDIR/src
VYOS_KCONF=$VYOS_BUILD/scripts/package-build/linux-kernel/config
OUT=$BUILD/debs
JOBS=${JOBS:-$(nproc)}

export ARCH=arm64 CROSS_COMPILE=aarch64-linux-gnu-
export KBUILD_BUILD_USER=mono KBUILD_BUILD_HOST=vyos-build

mkdir -p "$KDIR" "$OUT"

# Build from an exported tree, as VyOS builds from the kernel.org tarball: a
# git checkout would make setlocalversion append "+" to the release string.
head=$(git -C "$TREE" rev-parse HEAD)
if [ "$(cat "$SRC/.mono-tree" 2>/dev/null)" != "$head" ]; then
    echo "I: exporting tree $head -> $SRC"
    rm -rf "$SRC"; mkdir -p "$SRC"
    git -C "$TREE" archive "$head" | tar -x -C "$SRC"
    echo "$head" > "$SRC/.mono-tree"
fi
cd "$SRC"

echo "I: merging kernel config"
sed -i -e "s/CN =.*/CN=Mono Gateway VyOS build time autogenerated kernel key/" certs/default_x509.genkey
scripts/kconfig/merge_config.sh -m \
    "$VYOS_KCONF/arm64/vyos_defconfig" "$VYOS_KCONF"/*.config "$HERE/mono-ls1046a.config" \
    > "$KDIR/merge.log" 2>&1
make olddefconfig > /dev/null

# The fragment's intent must survive Kconfig dependency resolution; a symbol
# silently dropped here would ship a kernel that boots without its hardware.
fail=0
while read -r line; do
    case "$line" in ''|\#*) continue ;; esac
    sym=${line%%=*}; want=${line#*=}
    got=$(grep -E "^$sym=" .config | cut -d= -f2- || true)
    if [ "$got" != "$want" ]; then
        echo "E: $sym: wanted '$want', got '${got:-unset}'"; fail=1
    fi
done < <(grep -E '^CONFIG_' "$HERE/mono-ls1046a.config")
for sym in CONFIG_FSL_FMAN CONFIG_FSL_DPAA; do
    if grep -qE "^$sym=[ym]" .config; then echo "E: $sym must be off"; fail=1; fi
done
[ $fail -eq 0 ] || { echo "E: kernel config does not hold the board fragment"; exit 1; }
cp .config "$KDIR/config-$KERNEL_RELEASE"

echo "I: building kernel $KERNEL_RELEASE (bindeb-pkg, -j$JOBS)"
make -j"$JOBS" bindeb-pkg \
    LOCALVERSION=-${KERNEL_REVISION}-${KERNEL_FLAVOR} \
    KDEB_PKGVERSION=${KERNEL_VERSION}-${KERNEL_REVISION} \
    > "$KDIR/build.log" 2>&1 || { tail -40 "$KDIR/build.log"; exit 1; }
[ "$(make -s kernelrelease LOCALVERSION=-${KERNEL_REVISION}-${KERNEL_FLAVOR})" = "$KERNEL_RELEASE" ] \
    || { echo "E: kernelrelease is not $KERNEL_RELEASE"; exit 1; }

echo "I: building ASK modules (cdx, ask_flowtable)"
ASKSRC=$KDIR/ask-cdx
rm -rf "$ASKSRC"; cp -a "$BUILD/ask/cdx" "$ASKSRC"
make -C "$SRC" M="$ASKSRC" -j"$JOBS" PLATFORM=LS1046A KERNELDIR="$SRC" \
    CONFIG_ASK_CDX=m modules > "$KDIR/ask-modules.log" 2>&1 \
    || { tail -40 "$KDIR/ask-modules.log"; exit 1; }
for m in cdx ask_flowtable; do
    "$CROSS_COMPILE"strip --strip-debug "$ASKSRC/$m.ko"
    scripts/sign-file sha512 certs/signing_key.pem certs/signing_key.x509 "$ASKSRC/$m.ko"
done

rm -f "$OUT"/linux-*.deb
mv -f "$KDIR"/linux-*.deb "$OUT"/
rm -f "$OUT"/linux-image-*-dbg_*.deb
# Every module .deb must be signed with this kernel's key (MODULE_SIG_FORCE);
# build-iso.sh refuses packages built against another one.
sha256sum < certs/signing_key.x509 | cut -d' ' -f1 > "$OUT/.kernel-key"
echo "I: kernel done: $(ls "$OUT" | tr '\n' ' ')"
